<p>Un client anglophone entre dans votre boutique, à l'hôtel, au bureau ou au port. Pas besoin de parler parfaitement : avec quelques phrases polies et claires, vous l'accueillez bien, vous comprenez ce qu'il veut et il repart satisfait. Voici les phrases, étape par étape.</p>

<h2>1. Accueillir</h2>
<ul class="phrases">
    <x-phrase en="Good morning, welcome!" fr="Bonjour, bienvenue !" />
    <x-phrase en="How can I help you?" fr="Comment puis-je vous aider ?" />
    <x-phrase en="Please, have a seat." fr="Asseyez-vous, je vous en prie." />
</ul>

<h2>2. Comprendre la demande</h2>
<ul class="phrases">
    <x-phrase en="What are you looking for?" fr="Que cherchez-vous ?" />
    <x-phrase en="Could you tell me a little more?" fr="Pourriez-vous m'en dire un peu plus ?" />
    <x-phrase en="Sorry, could you speak more slowly?" fr="Pardon, pourriez-vous parler plus lentement ?" />
    <x-phrase en="Let me check that for you." fr="Je vérifie pour vous." />
</ul>
<p class="tip"><strong>Astuce :</strong> « Could you…? » est plus poli que « Can you…? ». Avec un client, préférez « Could you ».</p>

