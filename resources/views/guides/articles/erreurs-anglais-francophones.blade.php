<p>Le français et l'anglais partagent beaucoup de mots. C'est une chance, et c'est aussi un piège : on traduit mot à mot, et la phrase sonne faux. Voici vingt erreurs que l'on entend souvent chez les francophones, la bonne forme, et une astuce pour s'en souvenir.</p>

<h2>Les constructions traduites du français</h2>
<ol class="errors">
    <li><strong>« I have 20 years. »</strong> → <span lang="en-US">I'm 20 (years old).</span> En anglais, on « est » un âge.</li>
    <li><strong>« I am agree. »</strong> → <span lang="en-US">I agree.</span> « Agree » est déjà un verbe.</li>
    <li><strong>« It depends of the weather. »</strong> → <span lang="en-US">It depends on the weather.</span></li>
    <li><strong>« I am here since Monday. »</strong> → <span lang="en-US">I have been here since Monday.</span> Une action qui dure jusqu'à maintenant se dit avec « have been ».</li>
    <li><strong>« I explain you the lesson. »</strong> → <span lang="en-US">I explain the lesson to you.</span></li>
    <li><strong>« Can you say me the price? »</strong> → <span lang="en-US">Can you tell me the price?</span> On « tell » quelqu'un ; on « say » quelque chose.</li>
    <li><strong>« We are five. »</strong> → <span lang="en-US">There are five of us.</span></li>
</ol>

<h2>Les faux amis</h2>
<p>Des mots qui se ressemblent, mais qui ne veulent pas dire la même chose.</p>
<ol class="errors" start="8">
    <li><strong>« Actually »</strong> ne veut pas dire « actuellement », mais « en fait ». Actuellement se dit <span lang="en-US">currently</span> ou <span lang="en-US">right now</span>.</li>
    <li><strong>« Eventually »</strong> veut dire « finalement », pas « éventuellement ». Éventuellement se dit <span lang="en-US">possibly</span>.</li>
    <li><strong>« Library »</strong> est une bibliothèque. Une librairie se dit <span lang="en-US">bookstore</span>.</li>
    <li><strong>« Sensible »</strong> veut dire « raisonnable ». Sensible se dit <span lang="en-US">sensitive</span>.</li>
    <li><strong>« Assist »</strong> veut dire « aider ». Assister à une réunion se dit <span lang="en-US">attend a meeting</span>.</li>
    <li><strong>« Formation »</strong> n'est pas une formation professionnelle : on dit <span lang="en-US">training</span>.</li>
</ol>

<h2>Les petits mots</h2>
<ol class="errors" start="14">
    <li><strong>« People is nice. »</strong> → <span lang="en-US">People are nice.</span> « People » est pluriel.</li>
    <li><strong>« I'm teacher. »</strong> → <span lang="en-US">I'm a teacher.</span> Devant un métier, on met « a » ou « an ».</li>
    <li><strong>« She work in a bank. »</strong> → <span lang="en-US">She works in a bank.</span> Au présent, « he », « she » et « it » prennent un « s ».</li>
    <li><strong>« The life is beautiful. »</strong> → <span lang="en-US">Life is beautiful.</span> Pour parler d'une idée en général, pas de « the ».</li>
    <li><strong>« Informations », « advices »</strong> → <span lang="en-US">information, advice</span>. Ces mots n'ont pas de pluriel en anglais.</li>
</ol>

<h2>La prononciation</h2>
<ol class="errors" start="19">
    <li><strong>Le « h » muet.</strong> En anglais, le « h » se souffle : <span lang="en-US">house, happy, hello</span>. Sans lui, « hair » (cheveux) devient « air » (l'air).</li>
    <li><strong>Le « th ».</strong> Ni « z », ni « s » : la langue entre les dents. <span lang="en-US">Think, three, this, mother</span>.</li>
</ol>

<h2>Comment s'en débarrasser</h2>
<p>Lire la liste ne suffit pas : une erreur disparaît quand on a redit plusieurs fois la bonne forme, à voix haute, dans une vraie phrase. Choisissez deux erreurs qui vous concernent, et entraînez-vous dessus cette semaine. Pendant les séances, {{ $teacher }} vous laisse d'abord chercher, vous donne un indice, puis vous fait redire la phrase entière ; il garde vos erreurs et vous les fait revoir jusqu'à ce que vous les corrigiez deux fois de suite.</p>
