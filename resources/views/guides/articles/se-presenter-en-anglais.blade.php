<p>Se présenter, c'est souvent la première chose que l'on vous demande en anglais : à l'école, en entretien, au téléphone ou face à un visiteur. Bonne nouvelle : quelques phrases suffisent, et elles servent toute la vie. Voici comment les construire, de la plus simple à la plus complète.</p>

<h2>1. Dire bonjour et son nom</h2>
<p>Commencez par saluer, puis dites votre nom. « Hi » est détendu, « Hello » convient partout, « Good morning » (le matin) et « Good afternoon » (l'après-midi) sont plus polis.</p>
<ul class="phrases">
    <x-phrase en="Hello, my name is Kossi." fr="Bonjour, je m'appelle Kossi." />
    <x-phrase en="Hi, I'm Afi." fr="Salut, moi c'est Afi." />
    <x-phrase en="Nice to meet you." fr="Enchanté(e)." />
</ul>
<p class="tip"><strong>Astuce :</strong> « I'm » est la forme courte de « I am ». À l'oral, on dit presque toujours « I'm ».</p>

<h2>2. Dire son âge et d'où l'on vient</h2>
<p>En anglais, on « est » un âge : on ne l'« a » pas. C'est l'une des erreurs les plus fréquentes des francophones.</p>
<ul class="phrases">
    <x-phrase en="I'm 24 years old." fr="J'ai 24 ans." />
    <x-phrase en="I'm 24." fr="J'ai 24 ans (plus court, tout aussi correct)." />
    <x-phrase en="I'm from Togo." fr="Je viens du Togo." />
    <x-phrase en="I live in Lomé." fr="J'habite à Lomé." />
</ul>
<p>On ne dit jamais « I have 24 years » : c'est du français traduit mot à mot.</p>

<h2>3. Parler de son métier ou de ses études</h2>
<p>Devant un métier, l'anglais met « a » ou « an » : « I'm a teacher », jamais « I'm teacher ». On met « an » devant un son de voyelle : « an engineer », « an accountant ».</p>
<ul class="phrases">
    <x-phrase en="I'm a nurse." fr="Je suis infirmier (infirmière)." />
    <x-phrase en="I work as a sales assistant." fr="Je travaille comme vendeur (vendeuse)." />
    <x-phrase en="I'm a student at the University of Lomé." fr="Je suis étudiant(e) à l'université de Lomé." />
    <x-phrase en="I'm studying law." fr="J'étudie le droit." />
    <x-phrase en="I'm in eleventh grade." fr="Je suis en première (onzième année d'école)." />
</ul>

<h2>4. Parler de ses goûts</h2>
<p>Pour aller plus loin qu'une fiche d'identité, dites ce que vous aimez. Après « like », « love » et « enjoy », le verbe prend souvent la forme en « -ing ».</p>
<ul class="phrases">
    <x-phrase en="I like reading and playing soccer." fr="J'aime lire et jouer au football." />
    <x-phrase en="I love cooking for my family." fr="J'adore cuisiner pour ma famille." />
    <x-phrase en="In my free time, I listen to music." fr="Pendant mon temps libre, j'écoute de la musique." />
</ul>
<p class="tip"><strong>Anglais américain :</strong> on dit « soccer » pour le football. « Football » désigne, en anglais américain, un autre sport.</p>

<h2>5. Une présentation complète, en trente secondes</h2>
<p>Mettez tout ensemble. Voici un exemple à adapter à votre vie, puis à dire à voix haute plusieurs fois :</p>
<ul class="phrases">
    <x-phrase en="Hello, my name is Akosua. I'm 27 years old and I live in Lomé. I'm an accountant in a small company. In my free time, I like reading and going to church with my family. I'm learning English because I want to work with international clients." fr="Bonjour, je m'appelle Akosua. J'ai 27 ans et j'habite à Lomé. Je suis comptable dans une petite entreprise. Pendant mon temps libre, j'aime lire et aller à l'église en famille. J'apprends l'anglais parce que je veux travailler avec des clients étrangers." />
</ul>

<h2>6. Répondre quand quelqu'un se présente</h2>
<p>Une présentation est un échange. Après la vôtre, posez une question à votre tour :</p>
<ul class="phrases">
    <x-phrase en="And you? What do you do?" fr="Et vous ? Que faites-vous dans la vie ?" />
    <x-phrase en="Where are you from?" fr="D'où venez-vous ?" />
    <x-phrase en="It was nice talking to you." fr="J'ai été content(e) de parler avec vous." />
</ul>

<h2>Les erreurs à éviter</h2>
<ul>
    <li><strong>« I have 24 years »</strong> : dites « I'm 24 years old ».</li>
    <li><strong>« I'm teacher »</strong> : dites « I'm a teacher ».</li>
    <li><strong>« My name's is »</strong> : choisissez « My name is » ou « My name's », pas les deux.</li>
    <li><strong>« I'm agree »</strong> (pour réagir) : dites « I agree ».</li>
</ul>

<h2>Comment s'entraîner</h2>
<p>Écrivez votre présentation, lisez-la à voix haute, puis redites-la sans la regarder. Recommencez le lendemain : c'est en la disant plusieurs jours de suite qu'elle devient naturelle. L'idéal est de la dire à quelqu'un qui vous répond et vous corrige : c'est ce que fait {{ $teacher }} pendant l'évaluation orale gratuite, qui commence par des questions simples sur vous.</p>
