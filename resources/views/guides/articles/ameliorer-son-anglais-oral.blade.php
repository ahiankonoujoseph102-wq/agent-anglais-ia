<h2>4. Se faire corriger, puis redire</h2>
<p>Une erreur que personne ne corrige s'installe. La bonne méthode : vous dites votre phrase, quelqu'un vous donne un indice, vous cherchez la bonne forme, puis vous redites la phrase entière correctement. C'est en la redisant qu'elle se fixe.</p>
<p class="tip"><strong>Exemple :</strong> vous dites « Yesterday I go to work ». On vous rappelle : « Yesterday… c'est le passé. » Vous corrigez : « Yesterday I went to work. » Et vous la redites deux fois.</p>

<h2>5. Revoir ce que vous avez appris</h2>
<p>Reprenez les phrases de la veille avant d'en apprendre de nouvelles, puis revoyez-les quelques jours plus tard. Une phrase revue à plusieurs jours d'intervalle reste bien plus longtemps qu'une phrase vue une seule fois.</p>

<h2>6. Penser en anglais, avec des phrases simples</h2>
<p>Dites dans votre tête, en anglais, ce que vous faites : « I'm making tea. I'm going to work. It's hot today. » Ces petites phrases entraînent le cerveau à construire l'anglais sans passer par le français.</p>

<h2>7. Parler de votre vie</h2>
<p>On retient mieux ce qui nous concerne. Préparez des phrases sur votre métier, votre ville, votre famille, vos projets. Si vous travaillez au port, apprenez à parler d'un chargement ; si vous êtes étudiant, de vos cours.</p>

<h2>Un exemple de quinze minutes</h2>
<ol>
    <li>Trois minutes : redire les phrases de la veille.</li>
    <li>Cinq minutes : apprendre quatre ou cinq phrases nouvelles et les répéter.</li>
    <li>Cinq minutes : les utiliser dans une petite conversation.</li>
    <li>Deux minutes : noter la phrase à retenir pour demain.</li>
</ol>
