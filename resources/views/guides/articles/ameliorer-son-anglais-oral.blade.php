<p>Beaucoup de francophones comprennent l'anglais écrit, ont eu de bonnes notes à l'école, et pourtant bloquent dès qu'il faut parler. Ce n'est pas un manque d'intelligence : c'est un manque de pratique. L'oral est un savoir-faire, comme conduire : il s'entraîne. Voici comment.</p>

<h2>1. Parler un peu, mais tous les jours</h2>
<p>La régularité compte plus que la durée. Quinze minutes de vraie parole chaque jour font plus de progrès qu'une longue séance par semaine. Fixez un moment de la journée et gardez-le.</p>

<h2>2. Écouter de l'anglais simple et réel</h2>
<p>Choisissez des vidéos ou des émissions un peu au-dessus de votre niveau, pas beaucoup plus. Écoutez la même courte séquence plusieurs fois : la première pour le sens, les suivantes pour les mots et la musique de la phrase.</p>

<h2>3. Répéter des phrases entières</h2>
<p>Répétez à voix haute des phrases complètes, avec le même rythme que le modèle. Les mots courts (« a », « the », « to ») se prononcent souvent très vite en anglais : c'est ce qui rend la langue difficile à comprendre au début.</p>
